#!/usr/bin/env python3
"""
CIRCArt — copy the deck from artline.json into the online database.

artline.json stays the master. Run this after every change to it
(patch_cards.py, resolve.py, hand edits):

    python sync_deck.py www/artline.json                 # dry run: report only
    python sync_deck.py www/artline.json --sql deck.sql  # write SQL to paste into Supabase
    python sync_deck.py www/artline.json --push          # upload directly

--push needs two environment variables (Supabase → Project settings → API):
    SUPABASE_URL           https://xxxx.supabase.co
    SUPABASE_SERVICE_KEY   the *service_role* key. Keep it on your computer only;
                           never put it in the app or commit it.

What it does
  * gives every card a year-free key (stored in card_keys.json, see card_keys.py)
  * points image_url at  <site>/art/<key>.jpg, which build_deploy.py publishes
  * repairs broken characters such as "AbramoviÄ‡" → "Abramović" in the
    database copy and lists them, so you can fix artline.json too
  * marks cards that disappeared from artline.json as inactive instead of
    deleting them, so old games keep their history
"""

import argparse
import json
import os
import sys
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from card_keys import load_keys, image_name  # noqa: E402

SITE = "https://circart.langschwerts.de"     # same domain as build_deploy.py
TIER_BY_LABEL = {"icon": 1, "recognisable": 2, "recognizable": 2, "obscure": 3}
TEXT_FIELDS = ("title", "artist", "date_note", "movement", "medium", "location", "trivia")


def fix_mojibake(s):
    """UTF-8 text that was once read as Windows-1252, e.g. 'Ä‡' instead of 'ć'."""
    if not isinstance(s, str) or not any(ch in s for ch in "ÃÄÅÂâ"):
        return s
    try:
        fixed = s.encode("cp1252").decode("utf-8")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return s
    return fixed if fixed != s else s


def build_rows(cards, keys, site):
    rows, problems, repaired = [], [], []
    seen = set()
    for c in cards:
        cid = c.get("id")
        if not cid:
            problems.append(f"card without id: {c.get('title')}")
            continue
        if cid in seen:
            problems.append(f"duplicate id: {cid}")
            continue
        seen.add(cid)
        if not isinstance(c.get("year"), int):
            problems.append(f"{cid}: year is not a whole number ({c.get('year')!r})")
            continue

        texts = {}
        for f in TEXT_FIELDS:
            v = c.get(f)
            fv = fix_mojibake(v)
            if fv != v:
                repaired.append(f"{cid}.{f}: {v[:40]!r} → {fv[:40]!r}")
            texts[f] = fv

        tier = c.get("tier") if c.get("tier") in (1, 2, 3) else TIER_BY_LABEL.get(c.get("tier_label"), 2)
        has_image = bool(image_name(c))
        rows.append({
            "id": keys[cid],
            "source_id": cid,
            "title": texts["title"],
            "artist": texts["artist"],
            "year": c["year"],
            "date_note": texts["date_note"],
            "movement": texts["movement"],
            "medium": texts["medium"],
            "location": texts["location"],
            "tier": tier,
            "explicit": bool(c.get("explicit")),
            "visual_type": c.get("visual_type") or "object",
            "image_url": f"{site}/art/{keys[cid]}.jpg" if has_image else None,
            "trivia": texts["trivia"],
            "wikidata_qid": c.get("wikidata_qid"),
            "active": True,
        })
        if not has_image:
            problems.append(f"{cid}: no image_local")
    return rows, problems, repaired


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def to_sql(rows):
    cols = list(rows[0].keys())
    out = [f"-- generated by sync_deck.py ({len(rows)} cards)",
           f"insert into public.cards ({', '.join(cols)}) values"]
    out.append(",\n".join("(" + ", ".join(q(r[c]) for c in cols) + ")" for r in rows))
    out.append("on conflict (id) do update set " +
               ", ".join(f"{c} = excluded.{c}" for c in cols if c != "id") +
               ", updated_at = now();")
    ids = ", ".join(q(r["id"]) for r in rows)
    out.append(f"update public.cards set active = false, updated_at = now() "
               f"where active and id not in ({ids});")
    return "\n".join(out) + "\n"


def push(rows):
    url = os.environ.get("SUPABASE_URL", "").rstrip("/")
    key = os.environ.get("SUPABASE_SERVICE_KEY", "")
    if not url or not key:
        sys.exit("Set SUPABASE_URL and SUPABASE_SERVICE_KEY first (see the top of this file).")
    headers = {"apikey": key, "Authorization": f"Bearer {key}", "Content-Type": "application/json"}

    def call(method, path, body, extra=None):
        req = urllib.request.Request(url + path, data=json.dumps(body).encode(), method=method,
                                     headers={**headers, **(extra or {})})
        with urllib.request.urlopen(req) as r:
            return r.status

    call("POST", "/rest/v1/cards?on_conflict=id", rows,
         {"Prefer": "resolution=merge-duplicates,return=minimal"})
    ids = ",".join(r["id"] for r in rows)
    call("PATCH", f"/rest/v1/cards?active=is.true&id=not.in.({ids})", {"active": False},
         {"Prefer": "return=minimal"})
    print(f"Pushed {len(rows)} cards to {url}.")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("deck", nargs="?", default="www/artline.json")
    ap.add_argument("--sql", help="write SQL to this file")
    ap.add_argument("--push", action="store_true", help="upload to Supabase")
    ap.add_argument("--site", default=SITE, help="where docs/ is published")
    a = ap.parse_args()

    cards = json.loads(Path(a.deck).read_text(encoding="utf-8"))
    keys, added, key_file = load_keys([c for c in cards if c.get("id")])
    rows, problems, repaired = build_rows(cards, keys, a.site.rstrip("/"))

    tiers = {t: sum(1 for r in rows if r["tier"] == t) for t in (1, 2, 3)}
    print(f"{len(rows)} cards ready · icon {tiers[1]} · recognisable {tiers[2]} · obscure {tiers[3]}"
          f" · explicit {sum(r['explicit'] for r in rows)}")
    print(f"keys: {key_file} ({added} new)")
    if repaired:
        print(f"\nRepaired {len(repaired)} broken character(s) in the database copy "
              f"(fix these in artline.json too):")
        for r in repaired:
            print("  ~", r)
    if problems:
        print(f"\n{len(problems)} problem(s):")
        for p in problems:
            print("  !", p)

    if a.sql:
        Path(a.sql).write_text(to_sql(rows), encoding="utf-8")
        print(f"\nSQL written to {a.sql}")
    if a.push:
        push(rows)
    if not a.sql and not a.push:
        print("\nDry run. Add --sql deck.sql or --push to sync.")


if __name__ == "__main__":
    main()
