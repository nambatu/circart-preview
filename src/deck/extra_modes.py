#!/usr/bin/env python3
"""
CIRCArt — build helpers for Price Mode and Weekly Restoration paintings.

Pure Python + Pillow (no numpy). Imported by build_preview.py, build_deploy.py,
and stage.py, and callable from the CLI (e.g. from src/tools/test_all.sh).
"""

import argparse
import hashlib
import json
import math
import random
import re
import shutil
import sys
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageEnhance, ImageFilter, ImageOps
except ImportError:
    sys.exit("Pillow is not installed. Run:  pip install pillow")

WEEKLY_MAX_WIDTH = 640
PATCH_BLUR_RADIUS = 18
VARNISH_BLUR_RADIUS = 3.5


def sql_q(v):
    """Hardened SQL literal escaping matching sync_deck.q and build_preview.sql_q."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    s = str(v)
    if "\x00" in s:
        raise ValueError("NUL byte not allowed in SQL string")
    if "\\" in s or any(ord(ch) < 32 or ord(ch) == 127 for ch in s):
        out = []
        for ch in s:
            if ch == "\\":
                out.append("\\\\")
            elif ch == "'":
                out.append("''")
            elif ch == "\n":
                out.append("\\n")
            elif ch == "\r":
                out.append("\\r")
            elif ch == "\t":
                out.append("\\t")
            elif ord(ch) < 32 or ord(ch) == 127:
                out.append(f"\\x{ord(ch):02x}")
            else:
                out.append(ch)
        return "E'" + "".join(out) + "'"
    return "'" + s.replace("'", "''") + "'"


def _sql_text_array(items):
    if not items:
        return "'{}'::text[]"
    return "ARRAY[" + ", ".join(sql_q(str(x)) for x in items) + "]"


def _resolve_image(art_sources, candidates):
    """Find an existing image path in art_sources (dict or iterable of dirs)."""
    clean = []
    for cand in candidates:
        if not cand:
            continue
        c_str = str(cand).replace("\\", "/")
        if ".." in Path(c_str).parts:
            continue
        clean.append(cand)
        base = Path(c_str).name
        if base and base != cand:
            clean.append(base)
            clean.append(Path(base).stem)

    if isinstance(art_sources, dict):
        for key in clean:
            p = art_sources.get(key)
            if p is not None and Path(p).is_file():
                return Path(p)
        dirs = [Path(v) for v in art_sources.values() if v is not None and Path(v).is_dir()]
    elif isinstance(art_sources, (str, Path)):
        p = Path(art_sources)
        dirs = [p] if p.is_dir() else []
    else:
        dirs = [Path(d) for d in (art_sources or []) if d is not None and Path(d).is_dir()]

    for d in dirs:
        for key in clean:
            name = Path(str(key)).name
            if not name:
                continue
            for fn in (name, f"{name}.jpg"):
                cand_path = d / fn
                if cand_path.is_file():
                    return cand_path
    return None


def _verify_jpeg(path):
    with Image.open(path) as im:
        im.verify()


def process_price_deck(app_price_json, out_docs, art_sources, card_keys_mod, site):
    """Validate price-deck.json, copy art/<key>.jpg into out_docs/art, normalize JSON, and return SQL."""
    out_docs = Path(out_docs)
    art_dir = out_docs / "art"
    art_dir.mkdir(parents=True, exist_ok=True)

    raw_cards = json.loads(Path(app_price_json).read_text(encoding="utf-8"))
    if not isinstance(raw_cards, list) or not raw_cards:
        raise ValueError("price-deck.json must be a non-empty JSON array")

    required = (
        "id", "source_id", "title", "artist", "year", "medium", "location",
        "image_local", "price_usd_today", "sale_price_display", "sale_year",
        "auction_house", "story", "story_de",
    )
    seen_ids = set()
    for idx, c in enumerate(raw_cards):
        for field in required:
            if field not in c or c[field] in (None, ""):
                raise ValueError(f"price-deck.json[{idx}] missing required field {field!r}")
        cid = c["id"]
        if cid in seen_ids:
            raise ValueError(f"price-deck.json duplicate id {cid!r}")
        seen_ids.add(cid)
        if not isinstance(c["year"], int) or not isinstance(c["sale_year"], int):
            raise ValueError(f"price-deck.json[{cid}] year and sale_year must be integers")
        if not isinstance(c["price_usd_today"], int) or c["price_usd_today"] <= 0:
            raise ValueError(f"price-deck.json[{cid}] price_usd_today must be a positive integer")

    keys, _, _ = card_keys_mod.load_keys([{"id": c["id"]} for c in raw_cards])
    base_site = (site or "").rstrip("/")

    norm_cards = []
    sql = ["-- generated by extra_modes.py: Price Mode cards (inactive in classic deck, pack_id = null)"]
    for c in raw_cards:
        cid = c["id"]
        key = keys[cid]
        if not re.fullmatch(r"[a-z0-9_-]+", key):
            raise ValueError(f"Invalid card key {key!r} for {cid!r}")
        orig_name = Path(str(c["image_local"]).replace("\\", "/")).name
        orig_stem = Path(orig_name).stem

        dst_img = art_dir / f"{key}.jpg"
        src_img = dst_img if dst_img.is_file() else _resolve_image(
            art_sources, [cid, key, f"{key}.jpg", orig_name, orig_stem]
        )
        if src_img is None or not src_img.is_file():
            raise FileNotFoundError(
                f"Missing local image for price-deck card {cid!r} (looked for {key}.jpg / {orig_name})"
            )
        _verify_jpeg(src_img)
        if src_img.resolve() != dst_img.resolve():
            shutil.copy2(src_img, dst_img)

        norm = dict(c)
        norm["source_id"] = c.get("source_id") or cid
        norm["image_local"] = f"art/{key}.jpg"
        norm_cards.append(norm)

        if cid.startswith("price:"):
            img_url = f"{base_site}/art/{key}.jpg" if base_site else f"/art/{key}.jpg"
            cols = [
                "id", "source_id", "title", "artist", "year", "date_note",
                "movement", "medium", "location", "tier", "explicit",
                "visual_type", "image_url", "trivia", "pack_id", "active",
            ]
            vals = [
                key,
                cid,
                c["title"],
                c["artist"],
                int(c["year"]),
                c.get("date_note"),
                c.get("movement"),
                c["medium"],
                c["location"],
                int(c.get("tier") or 2),
                bool(c.get("explicit", False)),
                c.get("visual_type") or "object",
                img_url,
                c["story"],
                None,
                False,
            ]
            sql.append(
                f"insert into public.cards ({', '.join(cols)}) values ("
                + ", ".join(sql_q(v) for v in vals)
                + ") on conflict (id) do update set "
                "source_id = excluded.source_id, title = excluded.title, artist = excluded.artist, "
                "year = excluded.year, date_note = excluded.date_note, movement = excluded.movement, "
                "medium = excluded.medium, location = excluded.location, tier = excluded.tier, "
                "explicit = excluded.explicit, visual_type = excluded.visual_type, "
                "image_url = excluded.image_url, trivia = excluded.trivia, "
                "pack_id = null, active = false, updated_at = now();"
            )

    out_text = json.dumps(norm_cards, ensure_ascii=False, indent=2) + "\n"
    if "upload.wikimedia.org" in out_text:
        raise ValueError("price-deck.json output must never contain upload.wikimedia.org")
    (out_docs / "price-deck.json").write_text(out_text, encoding="utf-8")

    sql_text = "\n".join(sql) + "\n"
    if "upload.wikimedia.org" in sql_text:
        raise ValueError("price.sql must never contain upload.wikimedia.org")
    return sql_text


def _make_varnish(base, seed_str):
    """Create aged yellowed-varnish base with gentle blur and subtle craquelure."""
    w, h = base.size
    rng = random.Random(hashlib.sha256((seed_str + ":varnish").encode("utf-8")).digest())

    v = ImageEnhance.Color(base).enhance(0.45)        # desaturate ~55%
    v = ImageEnhance.Brightness(v).enhance(0.62)      # darken ~0.62
    # Warm amber/sepia glaze via 3x4 RGB matrix, then light amber blend
    v = v.convert("RGB", (
        0.84, 0.16, 0.04, 0,
        0.10, 0.76, 0.03, 0,
        0.02, 0.10, 0.56, 0,
    ))
    amber = Image.new("RGB", (w, h), (132, 96, 36))
    v = Image.blend(v, amber, 0.16)
    v = v.filter(ImageFilter.GaussianBlur(radius=VARNISH_BLUR_RADIUS))

    # Faint dark hairline craquelure across the aged varnish
    overlay = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(overlay)
    n_cracks = 24
    for _ in range(n_cracks):
        x = rng.uniform(0, w)
        y = rng.uniform(0, h)
        ang = rng.uniform(0, 2 * math.pi)
        steps = rng.randint(14, 28)
        pts = [(x, y)]
        for s in range(steps):
            ang += rng.uniform(-0.48, 0.48)
            step_len = rng.uniform(10, 26)
            x += math.cos(ang) * step_len
            y += math.sin(ang) * step_len
            pts.append((x, y))
            if s in (steps // 3, (2 * steps) // 3) and rng.random() < 0.7:
                bx, by = x, y
                bang = ang + rng.choice([-1, 1]) * rng.uniform(0.55, 1.1)
                bpts = [(bx, by)]
                for _b in range(rng.randint(5, 12)):
                    bang += rng.uniform(-0.45, 0.45)
                    blen = rng.uniform(8, 18)
                    bx += math.cos(bang) * blen
                    by += math.sin(bang) * blen
                    bpts.append((bx, by))
                alpha_b = rng.randint(24, 42)
                draw.line(bpts, fill=(32, 20, 10, alpha_b), width=1)
        alpha_m = rng.randint(28, 48)
        draw.line(pts, fill=(32, 20, 10, alpha_m), width=1)

    overlay = overlay.filter(ImageFilter.GaussianBlur(radius=0.5))
    out = Image.alpha_composite(v.convert("RGBA"), overlay).convert("RGB")
    return out


def _well_spread_centroids(w, h, rng):
    """Return 7 well-spread organic centroids shuffled across days 0..6."""
    # Stratified 2+3+2 or 4+3 grid depending on aspect ratio so every zone has ~1/7 area
    rows = [4, 3] if w >= h * 1.25 else [2, 3, 2]
    centers = []
    n_rows = len(rows)
    for r_idx, count in enumerate(rows):
        y0 = (r_idx + 0.5) * (h / n_rows)
        jy = rng.uniform(-0.18, 0.18) * (h / n_rows)
        for c_idx in range(count):
            x0 = (c_idx + 0.5) * (w / count)
            jx = rng.uniform(-0.18, 0.18) * (w / count)
            centers.append((x0 + jx, y0 + jy))
    rng.shuffle(centers)
    return centers


def _make_patches(base, seed_str):
    """Cut base RGB image into 7 soft-feathered RGBA zone PNGs (zero pixel leakage)."""
    w, h = base.size
    rng = random.Random(hashlib.sha256((seed_str + ":patches").encode("utf-8")).digest())
    centers = _well_spread_centroids(w, h, rng)

    # Half-res organic Voronoi assignment (fast pure Python, then resized cleanly)
    sw, sh = max(2, w // 2), max(2, h // 2)
    sc = [(cx * sw / w, cy * sh / h) for cx, cy in centers]
    p1, p2, p3, p4 = [rng.uniform(0, 2 * math.pi) for _ in range(4)]
    amp = max(4.0, min(sw, sh) * 0.075)
    f1, f2 = 2 * math.pi / max(sw, 1), 2 * math.pi / max(sh, 1)

    zones = bytearray(sw * sh)
    idx = 0
    for y in range(sh):
        sy_sin1 = math.sin(2.1 * f2 * y + p1)
        sy_cos2 = math.cos(3.3 * f2 * y + p2)
        for x in range(sw):
            wx = x + amp * (0.65 * math.sin(2.3 * f1 * x + 1.4 * f2 * y + p3) + 0.35 * sy_sin1)
            wy = y + amp * (0.65 * math.cos(1.9 * f1 * x + 2.7 * f2 * y + p4) + 0.35 * sy_cos2)
            best_k = 0
            best_d = 1e18
            for k, (cx, cy) in enumerate(sc):
                dx = wx - cx
                dy = wy - cy
                d = dx * dx + dy * dy
                if d < best_d:
                    best_d = d
                    best_k = k
            zones[idx] = best_k
            idx += 1

    black = Image.new("RGB", (w, h), (0, 0, 0))
    patches = []
    for k in range(7):
        raw_small = bytes(255 if z == k else 0 for z in zones)
        m_small = Image.frombytes("L", (sw, sh), raw_small)
        m_full = m_small.resize((w, h), Image.Resampling.BILINEAR).point(lambda v: 255 if v >= 128 else 0)
        soft = m_full.filter(ImageFilter.GaussianBlur(radius=PATCH_BLUR_RADIUS))

        # Keep RGB crisp where alpha > 0 (+2px margin for clean bilinear scaling), zero outside
        keep = soft.filter(ImageFilter.MaxFilter(5)).point(lambda a: 255 if a > 0 else 0)
        rgb = Image.composite(base, black, keep)
        rgba = rgb.convert("RGBA")
        rgba.putalpha(soft)
        patches.append(rgba)
    return patches


def _derive_artist_options(artist, year, week_start, card_rows_by_id):
    """Mirror 002_games._artist_options: real artist + 3 era-matched distractors, shuffled."""
    if not isinstance(card_rows_by_id, dict) or not card_rows_by_id:
        return None
    by_artist = {}
    for row in card_rows_by_id.values():
        if not isinstance(row, dict):
            continue
        if row.get("active") is False:
            continue
        a = row.get("artist")
        y = row.get("year")
        if not a or a == artist or not isinstance(y, int):
            continue
        dist = abs(y - year)
        if a not in by_artist or dist < by_artist[a]:
            by_artist[a] = dist

    near = sorted(a for a, d in by_artist.items() if d <= 150)
    far = sorted(a for a, d in by_artist.items() if d > 150)
    rng = random.Random(hashlib.sha256((week_start + ":artists").encode("utf-8")).digest())
    rng.shuffle(near)
    rng.shuffle(far)
    pool = (near + far)[:3]
    if len(pool) < 3:
        return None
    opts = [artist] + pool
    rng.shuffle(opts)
    return opts


def process_weekly_paintings(
    paintings_json,
    out_docs,
    art_sources,
    keys_by_source,
    card_rows_by_id,
    base_site,
    claude_cache=None,
):
    """Cut aged varnish + 7 feathered patch PNGs for each weekly painting and return weekly SQL."""
    out_docs = Path(out_docs)
    art_dir = out_docs / "art"
    art_dir.mkdir(parents=True, exist_ok=True)
    cache_dir = Path(claude_cache) if claude_cache else None
    if cache_dir is not None:
        cache_dir.mkdir(parents=True, exist_ok=True)

    entries = json.loads(Path(paintings_json).read_text(encoding="utf-8"))
    if not isinstance(entries, list):
        raise ValueError("paintings.json must be a JSON array")

    sql = ["-- generated by extra_modes.py: Weekly Restoration paintings"]
    seen_weeks = set()
    for e in entries:
        week_start = e["week_start"]
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", week_start):
            raise ValueError(f"Invalid week_start date: {week_start!r}")
        if week_start in seen_weeks:
            raise ValueError(f"Duplicate week_start in paintings.json: {week_start!r}")
        seen_weeks.add(week_start)

        raw_cid = e["card_id"]
        db_card_id = (keys_by_source or {}).get(raw_cid, raw_cid)
        row = (card_rows_by_id or {}).get(db_card_id) or (card_rows_by_id or {}).get(raw_cid) or {}

        candidates = [raw_cid, db_card_id, f"{db_card_id}.jpg", f"{raw_cid}.jpg"]
        if row.get("image_local"):
            candidates.append(Path(str(row["image_local"]).replace("\\", "/")).name)

        src_sources = [art_dir]
        if isinstance(art_sources, dict):
            src_sources = art_sources
        elif art_sources is not None:
            src_sources = list(art_sources) + [art_dir]

        src_img = _resolve_image(src_sources, candidates)
        if src_img is None and cache_dir is not None:
            src_img = _resolve_image([cache_dir], candidates)
        if src_img is None or not src_img.is_file():
            raise FileNotFoundError(
                f"Missing source image for weekly painting {week_start} ({raw_cid!r} / {db_card_id!r})"
            )

        h = hashlib.sha256(week_start.encode("utf-8")).hexdigest()[:10]
        prefix = f"wk-{h}"
        varnish_rel = f"art/{prefix}-varnish.jpg"
        patch_rels = [f"art/{prefix}-p{i}.png" for i in range(7)]

        stamp = f"{week_start}|{db_card_id}|{src_img.stat().st_size}"
        cache_hit = False
        if cache_dir is not None:
            stamp_file = cache_dir / f"{prefix}.stamp"
            if (
                stamp_file.is_file()
                and stamp_file.read_text(encoding="utf-8") == stamp
                and (cache_dir / f"{prefix}-varnish.jpg").is_file()
                and all((cache_dir / f"{prefix}-p{i}.png").is_file() for i in range(7))
            ):
                shutil.copy2(cache_dir / f"{prefix}-varnish.jpg", out_docs / varnish_rel)
                for i, rel in enumerate(patch_rels):
                    shutil.copy2(cache_dir / f"{prefix}-p{i}.png", out_docs / rel)
                cache_hit = True

        if not cache_hit:
            with Image.open(src_img) as raw_im:
                base = ImageOps.exif_transpose(raw_im).convert("RGB")
                if base.width > WEEKLY_MAX_WIDTH:
                    new_h = max(1, round(base.height * WEEKLY_MAX_WIDTH / base.width))
                    base = base.resize((WEEKLY_MAX_WIDTH, new_h), Image.Resampling.LANCZOS)

            varnish = _make_varnish(base, week_start)
            varnish.save(out_docs / varnish_rel, "JPEG", quality=84, optimize=True, progressive=True)
            patches = _make_patches(base, week_start)
            for patch, rel in zip(patches, patch_rels):
                patch.save(out_docs / rel, "PNG", optimize=True)

            if cache_dir is not None:
                shutil.copy2(out_docs / varnish_rel, cache_dir / f"{prefix}-varnish.jpg")
                for i, rel in enumerate(patch_rels):
                    shutil.copy2(out_docs / rel, cache_dir / f"{prefix}-p{i}.png")
                (cache_dir / f"{prefix}.stamp").write_text(stamp, encoding="utf-8")

        opts = e.get("artist_options")
        if not (isinstance(opts, list) and len(opts) == 4 and e["artist"] in opts):
            opts = _derive_artist_options(e["artist"], int(e["year"]), week_start, card_rows_by_id)

        opts_sql = (
            _sql_text_array(opts)
            if opts
            else f"(select public._artist_options(c) from public.cards c where c.id = {sql_q(db_card_id)})"
        )

        sql.append(
            "insert into public.weekly_paintings "
            "(week_start, card_id, varnish_url, patch_urls, artist_options, story, story_de) values ("
            + ", ".join([
                sql_q(week_start),
                sql_q(db_card_id),
                sql_q(varnish_rel),
                _sql_text_array(patch_rels),
                opts_sql,
                sql_q(e["story"]),
                sql_q(e["story_de"]),
            ])
            + ") on conflict (week_start) do update set "
            "card_id = excluded.card_id, varnish_url = excluded.varnish_url, "
            "patch_urls = excluded.patch_urls, artist_options = excluded.artist_options, "
            "story = excluded.story, story_de = excluded.story_de;"
        )

    return "\n".join(sql) + "\n"


def _build_card_lookup(artline_path, card_keys_mod, game_images_dir, pack_art_dir):
    """Build art_sources dict, keys_by_source, and card_rows_by_id from artline + pack-art."""
    art_sources = {}
    keys_by_source = {}
    card_rows_by_id = {}

    if artline_path and Path(artline_path).is_file():
        all_cards = [c for c in json.loads(Path(artline_path).read_text(encoding="utf-8")) if c.get("id")]
        keys, _, _ = card_keys_mod.load_keys(all_cards)
        keys_by_source.update(keys)
        for c in all_cards:
            cid = c["id"]
            k = keys[cid]
            row = dict(c)
            row["active"] = True
            card_rows_by_id[k] = row
            card_rows_by_id[cid] = row
            img = card_keys_mod.image_name(c)
            if img and game_images_dir:
                p = Path(game_images_dir) / img
                if p.is_file():
                    art_sources[k] = p
                    art_sources[f"{k}.jpg"] = p
                    art_sources[cid] = p
                    art_sources[img] = p

    if pack_art_dir and Path(pack_art_dir).is_dir():
        for p in sorted(Path(pack_art_dir).glob("*.jpg")):
            art_sources.setdefault(p.stem, p)
            art_sources.setdefault(p.name, p)

    return art_sources, keys_by_source, card_rows_by_id


def main():
    ap = argparse.ArgumentParser(description="Build Price Mode and Weekly Restoration assets + SQL.")
    ap.add_argument("--artline", help="path to artline.json")
    ap.add_argument("--card-keys", required=True, help="path to card_keys.json")
    ap.add_argument("--game-images", help="path to base docs/images directory")
    ap.add_argument("--pack-art", help="path to pack-art directory")
    ap.add_argument("--price-json", help="path to src/app/price-deck.json")
    ap.add_argument("--weekly-json", help="path to src/weekly/paintings.json")
    ap.add_argument("--out-docs", required=True, help="output docs directory (writes art/ + price-deck.json)")
    ap.add_argument("--price-sql", help="output SQL path for price.sql")
    ap.add_argument("--weekly-sql", help="output SQL path for weekly.sql")
    ap.add_argument("--site", default="", help="target site URL")
    ap.add_argument("--cache", help="optional cache directory for weekly patches")
    a = ap.parse_args()

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import card_keys  # noqa: E402

    card_keys.KEY_FILE = Path(a.card_keys)
    art_sources, keys_by_source, card_rows_by_id = _build_card_lookup(
        a.artline, card_keys, a.game_images, a.pack_art
    )

    out_docs = Path(a.out_docs)
    if a.price_json and Path(a.price_json).is_file():
        price_sql = process_price_deck(a.price_json, out_docs, art_sources, card_keys, a.site)
        if a.price_sql:
            Path(a.price_sql).write_text(price_sql, encoding="utf-8")

    if a.weekly_json and Path(a.weekly_json).is_file():
        weekly_sql = process_weekly_paintings(
            a.weekly_json, out_docs, art_sources, keys_by_source, card_rows_by_id, a.site, a.cache
        )
        if a.weekly_sql:
            Path(a.weekly_sql).write_text(weekly_sql, encoding="utf-8")


if __name__ == "__main__":
    main()
